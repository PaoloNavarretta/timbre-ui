// Turns every SVG in src/docs/assets/icons into a React component in src/icons.
// Run with `pnpm icons`. The SVG files are the single source: edit them, not the output.
import { readdir, readFile, writeFile } from "node:fs/promises";

const sourceDir = "src/docs/assets/icons";
const outputDir = "src/icons";

// "chevron-down.svg" → "ChevronDownIcon"
function componentName(file: string): string {
  const words = file.replace(".svg", "").split("-");
  return words.map((word) => word.charAt(0).toUpperCase() + word.slice(1)).join("") + "Icon";
}

// Keeps only the shapes inside <svg>…</svg> and closes empty tags JSX-style.
function shapes(svg: string): string {
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
  return inner.replace(/<(\w+)([^>]*)><\/\1>/g, "<$1$2 />");
}

const files = (await readdir(sourceDir)).filter((file) => file.endsWith(".svg")).sort();
const names: string[] = [];

for (const file of files) {
  const name = componentName(file);
  const svg = await readFile(`${sourceDir}/${file}`, "utf8");

  await writeFile(
    `${outputDir}/${name}.tsx`,
    `// Generated by scripts/generate-icons.ts from ${file}. Do not edit.
import { Icon, type IconProps } from "./Icon";

export function ${name}(props: Omit<IconProps, "children">) {
  return <Icon {...props}>${shapes(svg)}</Icon>;
}
`,
  );
  names.push(name);
}

await writeFile(
  `${outputDir}/index.ts`,
  `// Generated by scripts/generate-icons.ts. Do not edit.
export { Icon } from "./Icon";
export type { IconProps } from "./Icon";
${names.map((name) => `export { ${name} } from "./${name}";`).join("\n")}
`,
);

console.log(`Generated ${names.length} icons.`);

// Turns every SVG in src/docs/assets/icons into a React component in src/icons.
// Run with `pnpm icons`. The SVG files are the single source: edit them, not the output.
//
// Example, for one file:
//   src/docs/assets/icons/search.svg  →  src/icons/SearchIcon.tsx
// and, for all of them together:
//   src/icons/index.ts (one export per icon)
import { readdir, readFile, writeFile } from "node:fs/promises";

// Relative paths: the script runs from the repo root (`pnpm icons`).
const sourceDir = "src/docs/assets/icons";
const outputDir = "src/icons";

// File name → component name. Step by step, for "phone-hangup.svg":
//   .replace(".svg", "")   "phone-hangup"
//   .split("-")            ["phone", "hangup"]      the "-" is where it cuts, and it disappears
//   .map(…)                ["Phone", "Hangup"]      "h".toUpperCase() + "angup"
//   .join("")              "PhoneHangup"            without join: "Phone,Hangup" (arrays become text with commas)
//   + "Icon"               "PhoneHangupIcon"
// charAt(0) and slice(1) do not change `word`: strings never change, both return a new one.
// charAt(0) instead of word[0]: word[0] may be undefined for TypeScript, charAt always returns a string.
function componentName(file: string): string {
  const words = file.replace(".svg", "").split("-");
  return words.map((word) => word.charAt(0).toUpperCase() + word.slice(1)).join("") + "Icon";
}

// Keeps only the shapes inside <svg>…</svg> and closes empty tags JSX-style.
// Example, with search.svg (attributes shortened):
//   in:  <svg xmlns="…" viewBox="0 0 24 24" …><circle cx="11" cy="11" r="6.5"></circle><path d="M16 16l4 4"></path></svg>
//   out: <circle cx="11" cy="11" r="6.5" /><path d="M16 16l4 4" />
function shapes(svg: string): string {
  // 1. Delete everything up to the end of the opening tag.
  //    ^            from the very start of the text
  //    [\s\S]*?     any characters, as few as possible (skips a comment or <?xml?> if there is one)
  //    <svg         the literal text "<svg"
  //    [^>]*        every character that is not ">": the attributes
  //    >            the end of the opening tag
  //    → "<circle …></circle><path …></path></svg>\n"
  //
  // 2. Delete the closing tag at the end.
  //    <\/svg>      the literal text "</svg>" (\/ is a real "/", alone it would end the regex)
  //    \s*          spaces or line breaks, if any: the file ends with "\n"
  //    $            the very end of the text
  //    → "<circle …></circle><path …></path>"
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");

  // 3. An empty element becomes self-closing: <path d="…"></path> → <path d="…" />
  //    <(\w+)       "<" and a tag name, remembered as $1      e.g. "path"
  //    ([^>]*)      the attributes, remembered as $2          e.g. ' d="M16 16l4 4"'
  //    ><\/\1>      ">" then "</" + the same name as $1 + ">", with nothing in between
  //    g            every match, not only the first
  //    "<$1$2 />"   rebuilt with the remembered pieces        → '<path d="M16 16l4 4" />'
  // \1 makes a <g>…</g> with shapes inside stay as it is: only empty elements are closed.
  return inner.replace(/<(\w+)([^>]*)><\/\1>/g, "<$1$2 />");
}

// ["arrow-left.svg", "arrow-right.svg", "bell.svg", …]: only SVG files, sorted, so every run writes the same index.
// `await` outside a function works because the script is an ES module.
const files = (await readdir(sourceDir)).filter((file: string) => file.endsWith(".svg")).sort();
const names: string[] = [];

for (const file of files) {
  const name = componentName(file); // "search.svg" → "SearchIcon"
  const svg = await readFile(`${sourceDir}/${file}`, "utf8"); // the SVG as text

  // Writes src/icons/SearchIcon.tsx. The template literal is the same component
  // you would write by hand; ${name} and ${shapes(svg)} are filled in for each file.
  // Prettier (in `pnpm icons`) then formats it like the rest of the code.
  await writeFile(
    `${outputDir}/${name}.tsx`,
    `// Generated by scripts/generate-icons.ts from ${file}. Do not edit.
import { Icon, type IconProps } from "./Icon";

export function ${name}(props: Omit<IconProps, "children">) {
  return <Icon {...props}>${shapes(svg)}</Icon>;
}
`,
  );
  names.push(name);
}

// Writes src/icons/index.ts: the shell, its type, then one line per icon, e.g.
//   export { SearchIcon } from "./SearchIcon";
// join("\n") puts each export on its own line.
await writeFile(
  `${outputDir}/index.ts`,
  `// Generated by scripts/generate-icons.ts. Do not edit.
export { Icon } from "./Icon";
export type { IconProps } from "./Icon";
${names.map((name) => `export { ${name} } from "./${name}";`).join("\n")}
`,
);

console.log(`Generated ${names.length} icons.`);
